"""
docs/weather-codes.md: which icon each weather code shows, per code set of
boards/nspanel/nextion/weather-icons.json (one per openHAB weather add-on channel), with the
icons from boards/nspanel/nextion/assets/meteocons.

    python3 tools/gen_weather_doc.py

boards/nspanel/nextion/build.sh runs it; the file is committed.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SETS = ROOT / "boards" / "nspanel" / "nextion" / "weather-icons.json"
OUT = ROOT / "docs" / "weather-codes.md"
ICONS = "../boards/nspanel/nextion/assets/meteocons"   # relative to docs/


def icon(name):
    return f'<img src="{ICONS}/{name}.svg" width="40" alt=""> `{name}`'


def main():
    sets = json.loads(SETS.read_text())
    out = [
        "# Weather codes and icons",
        "",
        "<!-- Generated by tools/gen_weather_doc.py from boards/nspanel/nextion/weather-icons.json; do not edit. -->",
        "",
        "Home's weather icon and the weather pages show the icon for the code an",
        "openHAB item holds. `codes` in the configuration (`weather_icon`, weather",
        "pages) names the code set of the channel the item is linked to (see",
        "[panel-config.md](panel-config.md)); a code the set does not know shows",
        "the set's default.",
        "",
        "The icons are [Meteocons](https://github.com/basmilius/weather-icons) by",
        "Bas Milius (MIT), the fill style.",
        "",
        "| Code set | openHAB channel |",
        "|---|---|",
    ]
    for key, s in sets.items():
        out.append(f"| [`{key}`](#{key}) | {s['title']} |")
    for key, s in sets.items():
        out += ["", f"## {key}", "", s["title"] + ".", "", "| Code | Icon |", "|---|---|"]
        for code, name in s["codes"].items():
            out.append(f"| `{code}` | {icon(name)} |")
        out.append(f"| any other | {icon(s['default'])} |")
    text = "\n".join(out) + "\n"
    if not OUT.exists() or OUT.read_text() != text:
        OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {sum(len(s['codes']) for s in sets.values())} codes in {len(sets)} sets")


if __name__ == "__main__":
    main()
