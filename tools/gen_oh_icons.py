#!/usr/bin/env python3
"""
openHAB's icons as the panel's (components/app_display/openhab-icons.json) into
- components/app_display/src/OhIcons.cpp: the firmware's table, sorted by name (oh_icon() looks it up);
- www/index.html: the same for the preview (OH_ICONS), between its "oh-icons: begin" and "oh-icons: end" markers;
- docs/openhab-icons.md: the table as the documentation shows it.
Refused when an icon is not in the panel's icon font (boards/nspanel/nextion/icons.json, OHpanel's own excepted).

    tools/gen_oh_icons.py            # write
    tools/gen_oh_icons.py --check    # only say whether the files are current (exit 1 if not)
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "components" / "app_display" / "openhab-icons.json"
CPP = ROOT / "components" / "app_display" / "src" / "OhIcons.cpp"
WEB = ROOT / "www" / "index.html"
DOC = ROOT / "docs" / "openhab-icons.md"
FONT = ROOT / "boards" / "nspanel" / "nextion" / "icons.json"


FAMILIES = ("baby", "boy", "girl", "man", "woman", "parents")   # baby_1 .. parents_6_6: one entry for each


def resolved(icons):
    """The table with its aliases ("=battery") filled in."""
    return {name: icons[v[1:]] if isinstance(v, str) and v.startswith("=") else v for name, v in icons.items()}


def entries(icons):
    """(name, state, icon) sorted by name, then the states as the source has them."""
    out = []
    for name, v in sorted(icons.items()):
        for state, icon in ([("", v)] if isinstance(v, str) else v.items()):
            out.append((name, state, icon))
    return out


def cpp(icons):
    rows = entries(icons)
    lines = ["// generated by tools/gen_oh_icons.py from components/app_display/openhab-icons.json -- edit there",
             "/*",
             "   openHAB's icons (an item's category, the classic icon set's names) as the panel's Material Design Icons,",
             "   dynamic by the item's state as openHAB's are: oh_icon().",
             "*/",
             "",
             '#include "appdisplay/OhIcons.h"',
             "",
             '#include "appdisplay/Icons.h"',
             "",
             "#include <algorithm>",
             "#include <cctype>",
             "#include <cmath>",
             "#include <cstdlib>",
             "#include <cstring>",
             "",
             "namespace appdisplay {",
             "namespace {",
             "",
             "struct Entry {",
             "  const char *name;    // openHAB's icon",
             "  const char *state;   // \"\": without; \"on\", \"open\", a number (the largest not above the state)",
             "  const char *icon;    // the panel's",
             "};",
             "",
             "/* By name (sorted), each name's states in a row. */",
             "constexpr Entry kIcons[] = {"]
    for name, state, icon in rows:
        lines.append(f'    {{"{name}", "{state}", "{icon}"}},')
    lines += ["};",
              "",
              "bool numeric(const char *s, double &v) {",
              "  char *end = nullptr;",
              "  v = std::strtod(s, &end);",
              "  return *s && end && !*end;",
              "}",
              "",
              "}  // namespace",
              "",
              "std::string oh_icon(const std::string &category, const appoh::ItemState *state) {",
              "  std::string name;",
              "  for (const char c : category)",
              "    name += static_cast<char>(std::tolower(static_cast<unsigned char>(c)));",
              "  // openHAB 4's sources: an MDI icon as it is (where the icon font has it); openHAB's own (classic) icon set",
              "  // by its name",
              "  for (const char *mdi : {\"iconify:mdi:\", \"if:mdi:\", \"mdi:\"})",
              "    if (name.rfind(mdi, 0) == 0) {",
              "      name.erase(0, std::strlen(mdi));",
              "      return icon_glyph(name.c_str()).empty() ? std::string() : name;",
              "    }",
              "  for (const char *prefix : {\"oh:classic:\", \"oh:\", \"classic:\"})",
              "    if (name.rfind(prefix, 0) == 0)",
              "      name.erase(0, std::strlen(prefix));",
              "  const auto find = [](const std::string &n) {",
              "    return std::equal_range(std::begin(kIcons), std::end(kIcons), Entry{n.c_str(), \"\", \"\"},",
              "                            [](const Entry &a, const Entry &b) { return std::strcmp(a.name, b.name) < 0; });",
              "  };",
              "  auto range = find(name);",
              "  if (range.first == range.second) {   // baby_1 .. parents_6_6: one for each family",
              "    const std::string family = name.substr(0, name.find('_'));",
              "    for (const char *f : {" + ", ".join('\"%s\"' % f for f in FAMILIES) + "})",
              "      if (family == f && family.size() < name.size())",
              "        range = find(family);",
              "  }",
              "  if (range.first == range.second)",
              "    return {};",
              "  // the state as openHAB's dynamic icons name it: on, off, open, closed, a number, a text in lower case",
              "  std::string key;",
              "  double value = 0;",
              "  bool is_number = false;",
              "  if (state && !state->undefined()) {",
              "    if (state->has_numeric && state->state != \"ON\" && state->state != \"OFF\") {",
              "      is_number = true;",
              "      value = state->numeric;",
              "    } else {",
              "      for (const char c : state->state)",
              "        key += static_cast<char>(std::tolower(static_cast<unsigned char>(c)));",
              "    }",
              "  }",
              "  const Entry *plain = nullptr, *below = nullptr, *lowest = nullptr;",
              "  double below_at = -INFINITY, lowest_at = INFINITY;",
              "  for (auto e = range.first; e != range.second; ++e) {",
              "    double at = 0;",
              "    if (!*e->state)",
              "      plain = e;",
              "    else if (numeric(e->state, at)) {",
              "      if (is_number && at <= value && at > below_at)",
              "        below = e, below_at = at;",
              "      if (at < lowest_at)",
              "        lowest = e, lowest_at = at;",
              "    } else if (!is_number && key == e->state) {",
              "      return e->icon;",
              "    }",
              "  }",
              "  // only steps (a shield, a dryer) and a switch's or a contact's state: on/closed the top, off/open the bottom",
              "  if (!is_number && lowest) {",
              "    const bool top = key == \"on\" || key == \"closed\", bottom = key == \"off\" || key == \"open\";",
              "    if (top || bottom) {",
              "      const Entry *highest = lowest;",
              "      double highest_at = lowest_at;",
              "      for (auto e = range.first; e != range.second; ++e)",
              "        if (double at = 0; numeric(e->state, at) && at > highest_at)",
              "          highest = e, highest_at = at;",
              "      return (top ? highest : lowest)->icon;",
              "    }",
              "  }",
              "  if (below)",
              "    return below->icon;",
              "  if (is_number && lowest)",
              "    return lowest->icon;",
              "  if (plain)",
              "    return plain->icon;",
              "  // no state, or one it does not name: on/open as the item without one shows, else its first",
              "  for (const char *on : {\"on\", \"open\"})",
              "    for (auto e = range.first; e != range.second; ++e)",
              "      if (std::strcmp(e->state, on) == 0)",
              "        return e->icon;",
              "  return range.first->icon;",
              "}",
              "",
              "}  // namespace appdisplay",
              ""]
    return "\n".join(lines)


def js(icons):
    families = json.dumps(list(FAMILIES))
    return ("\n// generated by tools/gen_oh_icons.py from components/app_display/openhab-icons.json -- edit there\n"
            "const OH_FAMILIES = " + families + ";\n"
            "const OH_ICONS = " + json.dumps(icons, separators=(",", ":")) + ";\n")


def doc(icons):
    out = ["# openHAB's icons on the panel",
           "",
           "<!-- generated by tools/gen_oh_icons.py from components/app_display/openhab-icons.json -- edit there -->",
           "",
           "An item's icon in openHAB (its *category*, the names of openHAB's classic icon set) shows on the panel as one of",
           "its Material Design Icons: with `\"icon\": \"openhab\"` wherever an icon goes, and on a group's page for every",
           "member without an icon of its own (its metadata's comes first, the page's `icon` last). The icons change",
           "with the item's state as openHAB's dynamic icons do: `on`/`off`, `open`/`closed`/`ajar`, a number takes the",
           "largest step not above it. A category that names an MDI icon (`iconify:mdi:door-open`) shows that icon; one",
           "not in the table shows the page's icon.",
           "",
           "| openHAB | state | panel (MDI) |",
           "|---|---|---|"]
    for name, state, icon in entries(icons):
        shown = name + ("_1 … " + name + "_6" if name in FAMILIES[:-1] else
                        "_1_1 … parents_6_6" if name == "parents" else "")
        out.append(f"| `{shown}` | {('`' + state + '`') if state else '–'} | `{icon}` |")
    return "\n".join(out) + "\n"


def splice(text, begin, end, body):
    a = text.index(begin) + len(begin)
    b = text.index(end, a)
    return text[:a] + body + text[b:]


def main():
    check = "--check" in sys.argv
    icons = resolved(json.loads(SOURCE.read_text(encoding="utf-8"))["icons"])
    font = json.loads(FONT.read_text(encoding="utf-8"))
    missing = sorted({icon for _, _, icon in entries(icons) if icon not in font})
    if missing:
        sys.exit("gen_oh_icons: not in the icon font: " + ", ".join(missing))
    web = WEB.read_text(encoding="utf-8")
    jobs = [(CPP, cpp(icons)), (DOC, doc(icons)),
            (WEB, splice(web, "// oh-icons: begin", "// oh-icons: end", js(icons)))]
    stale = []
    for path, new in jobs:
        old = path.read_text(encoding="utf-8") if path.exists() else ""
        if new != old:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(new, encoding="utf-8")
    if check and stale:
        sys.exit("gen_oh_icons: not current, run tools/gen_oh_icons.py: " + ", ".join(map(str, stale)))
    print("gen_oh_icons: " + ("written " + ", ".join(map(str, stale)) if stale and not check else "current"))


if __name__ == "__main__":
    main()
