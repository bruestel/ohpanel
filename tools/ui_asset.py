"""
The web interface as the firmware embeds it: www/index.html without comments and
indentation (tools/strip_ui.py) and www/layout-<variant>.json (the preview's page
layouts of the panel variant's design, from boards/nspanel/nextion/tools/hmi2layout.py;
tools/variant.py), each gzipped, as C arrays in components/app_web/src/ui_asset.c.

Shared by the PlatformIO pre-build hook (tools/gen_ui_asset.py) and the CMake
fallback for plain idf.py builds (tools/gen_ui_asset_standalone.py), so both
write the same file and run the same checks.
"""

import gzip
import json
import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

TOOLS = pathlib.Path(__file__).resolve().parent
ROOT = TOOLS.parent
sys.path.insert(0, str(TOOLS))
import variant  # noqa: E402

SRC = ROOT / "www" / "index.html"
OUT = ROOT / "components" / "app_web" / "src" / "ui_asset.c"


def c_array(name, data):
    body = ",".join(f"0x{b:02x}" for b in data)
    return f"const unsigned char {name}[] = {{{body}}};\nconst unsigned int {name}_len = {len(data)};\n"


def generate(src=SRC, layout=None, out=OUT):
    """Writes `out` from `src` and `layout` (OHPANEL_VARIANT's when not given, tools/variant.py) -- only when its content changes, so ninja does not relink on every
    build. Refuses an interface that does not start and a layout that does not parse."""
    layout = layout or variant.layout(variant.current())
    for f in (src, layout):
        if not pathlib.Path(f).is_file():
            raise SystemExit(f"gen_ui_asset: {f} not found")
    from strip_ui import strip_html  # noqa: E402
    raw = strip_html(pathlib.Path(src).read_text()).encode()
    check_startup(raw)
    layout_bytes = pathlib.Path(layout).read_bytes()
    json.loads(layout_bytes)   # a broken file fails here, not as an empty preview
    # mtime=0 so the output is byte-identical for identical input, which keeps
    # rebuilds from churning just because the clock moved on.
    packed = gzip.compress(raw, compresslevel=9, mtime=0)
    text = (
        f"/* Generated by tools/ui_asset.py from www/index.html and www/{pathlib.Path(layout).name} -- do not edit. */\n"
        + c_array("ui_index_html_gz", packed)
        + c_array("ui_layout_json_gz", gzip.compress(layout_bytes, compresslevel=9, mtime=0))
    )
    out = pathlib.Path(out)
    if out.is_file() and out.read_text() == text:
        print(f"gen_ui_asset: unchanged ({len(raw)} -> {len(packed)} bytes)")
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"gen_ui_asset: index.html {len(raw)} -> {len(packed)} bytes gzip")


def check_startup(raw):
    """Refuse to embed an interface that cannot start.

    A variable declared below the code that reads it throws before anything
    renders, so the page comes up blank -- with the failure visible only in a
    console nobody has open, and often only on one #hash, so the other entry
    points keep working and hide it. That has happened twice here.

    Skipped rather than fatal when node is missing: a toolchain without it
    should still be able to build firmware.
    """
    checker = TOOLS / "check_ui.js"
    if not checker.is_file():
        return
    if shutil.which("node") is None:
        print("gen_ui_asset: node not found, skipping the startup check")
        return
    with tempfile.TemporaryDirectory() as tmp:
        page = pathlib.Path(tmp) / "index.html"
        page.write_bytes(raw)
        # the scripts parse (stripping went right), then the page starts
        script = page.with_suffix(".js")
        script.write_text("\n".join(re.findall(r"<script[^>]*>(.*?)</script>", page.read_text(), re.S)))
        result = subprocess.run(["node", "--check", str(script)], capture_output=True, text=True)
        if result.returncode != 0:
            raise SystemExit("gen_ui_asset: the stripped interface does not parse:\n" + result.stderr.strip())
        result = subprocess.run(["node", str(checker), str(page)], capture_output=True, text=True)
        if result.returncode != 0:
            raise SystemExit(result.stderr.strip() or "gen_ui_asset: the interface fails to start")
        # Printed so a passing check is visible too -- a guard nobody sees run is a
        # guard nobody trusts.
        print(result.stderr.strip())
