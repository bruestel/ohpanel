#!/usr/bin/env python3
"""
The panel's words in every display language, from components/app_display/texts.json into
- components/app_display/src/Format.cpp: one table of C strings per language (in flash; only the chosen
  language becomes a Texts, display_settings), the languages' decimal separator and default date format;
- www/index.html: the same for the preview (TEXTS, LANGUAGES) and the language choice;
- components/panel/src/Schema.cpp: the languages a configuration may name.
Each goes between its "texts: begin" and "texts: end" markers. Refused when a word has a letter the display's
text font (Ubuntu) lacks -- the display would leave it out -- or a boot label is longer than its field.

    tools/gen_texts.py            # write
    tools/gen_texts.py --check    # only say whether the files are current (exit 1 if not)
"""

import json
import pathlib
import struct
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "components" / "app_display" / "texts.json"
META = ("code", "name", "decimal", "group", "date")
WEB_ONLY = ("qr_wifi", "qr_password")   # the web interface's, not the panel's
FONT = ROOT / "boards" / "nspanel" / "nextion" / "assets" / "fonts" / "Ubuntu-R.ttf"   # the text fonts' source
BOOT_LABELS = ("boot_device", "boot_wifi", "boot_address")   # the boot page's narrow fields: 8 characters, 16 bytes


def font_characters(path):
    """The characters a TrueType font has: its cmap's Unicode BMP subtable (format 4)."""
    data = path.read_bytes()
    tables = {data[12 + 16 * i:16 + 16 * i]: struct.unpack(">I", data[20 + 16 * i:24 + 16 * i])[0]
              for i in range(struct.unpack(">H", data[4:6])[0])}
    cmap = tables[b"cmap"]
    for i in range(struct.unpack(">H", data[cmap + 2:cmap + 4])[0]):
        platform, encoding, offset = struct.unpack(">HHI", data[cmap + 4 + 8 * i:cmap + 12 + 8 * i])
        sub = cmap + offset
        if (platform, encoding) in ((3, 1), (0, 3)) and struct.unpack(">H", data[sub:sub + 2])[0] == 4:
            n = struct.unpack(">H", data[sub + 6:sub + 8])[0] // 2
            ends = struct.unpack(f">{n}H", data[sub + 14:sub + 14 + 2 * n])
            starts = struct.unpack(f">{n}H", data[sub + 16 + 2 * n:sub + 16 + 4 * n])
            return {chr(c) for a, b in zip(starts, ends) for c in range(a, b + 1) if c != 0xFFFF}
    sys.exit(f"gen_texts: {path.name} has no Unicode cmap")


def validate(langs):
    have = font_characters(FONT)
    problems = []
    for lang in langs:
        for k in fields(lang):
            for word in flatten(lang[k]):
                missing = sorted(set(word) - have)
                if missing:
                    problems.append(f"{lang['code']}.{k} \"{word}\": the font has no {''.join(missing)}")
        for k in BOOT_LABELS:
            if len(lang[k]) > 8 or len(lang[k].encode()) > 16:
                problems.append(f"{lang['code']}.{k} \"{lang[k]}\": 8 characters (16 bytes) at most")
        for k in ("decimal", "group"):
            if len(lang[k]) != 1 or not lang[k].isascii():
                problems.append(f"{lang['code']}.{k}: one ASCII character")
    if problems:
        sys.exit("gen_texts: " + "\n  ".join(["refused:"] + problems))


def flatten(value):
    if isinstance(value, list):
        return [s for v in value for s in flatten(v)]
    return [value]


def cpp_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def fields(lang):
    return [k for k in lang if k not in META and k not in WEB_ONLY and not k.startswith("_")]


def cpp(langs):
    keys = fields(langs[0])
    count = len(flatten([langs[0][k] for k in keys]))
    out = ["// generated by tools/gen_texts.py from components/app_display/texts.json -- edit there",
           f"constexpr int kTextCount = {count};",
           "/* Every language's words in the order fill_texts() reads them: C strings, in flash -- only the language",
           "   chosen becomes a Texts (display_settings). */",
           "const char *const kTextTable[][kTextCount] = {"]
    for lang in langs:
        strings = flatten([lang[k] for k in keys])
        assert len(strings) == count, lang["code"]
        out.append(f"    {{  // {lang['code']}")
        line = "       "
        for s in strings:
            item = " " + cpp_string(s) + ","
            if len(line) + len(item) > 116:
                out.append(line)
                line = "       "
            line += item
        out.append(line)
        out.append("    },")
    out.append("};")
    out.append("struct Language {")
    out.append("  const char *code;")
    out.append("  char decimal;        // before a number's decimals")
    out.append("  char group;          // between its thousands")
    out.append("  const char *date;    // display.date_format when it is not set")
    out.append("};")
    out.append("constexpr Language kLanguages[] = {")
    for lang in langs:
        out.append(f"    {{{cpp_string(lang['code'])}, '{lang['decimal']}', '{lang['group']}', {cpp_string(lang['date'])}}},")
    out.append("};")
    # the table's order, read back into a Texts
    out.append("void fill_texts(Texts &t, const char *const *s) {")
    i = 0
    sample = langs[0]
    for k in keys:
        v = sample[k]
        if not isinstance(v, list):
            out.append(f"  t.{k} = s[{i}];")
            i += 1
        elif not isinstance(v[0], list):
            out.append(f"  for (int k = 0; k < {len(v)}; k++) t.{k}[k] = s[{i} + k];")
            i += len(v)
        else:
            n, m = len(v), len(v[0])
            out.append(f"  for (int k = 0; k < {n} * {m}; k++) t.{k}[k / {m}][k % {m}] = s[{i} + k];")
            i += n * m
    out.append("}")
    return "\n".join(out)


def js(langs):
    out = ["// generated by tools/gen_texts.py from components/app_display/texts.json -- edit there",
           "const TEXTS = {"]
    for lang in langs:
        body = {k: lang[k] for k in lang if k not in META and not k.startswith("_")}
        out.append(f"  {lang['code']}: {json.dumps(body, ensure_ascii=False)},")
    out.append("};")
    out.append("const LANGUAGES = " + json.dumps({lang["code"]: {"name": lang["name"], "decimal": lang["decimal"],
                                                               "group": lang["group"], "date": lang["date"]} for lang in langs},
                                                  ensure_ascii=False) + ";")
    return "\n".join(out)


def options(langs):
    return "".join(f'<option value="{lang["code"]}">{lang["name"]}</option>' for lang in langs)


def schema(langs):
    return "    one_of(d, \"language\", path, {" + ", ".join(cpp_string(lang["code"]) for lang in langs) + "});"


def splice(text, begin, end, body, path):
    a = text.index(begin) + len(begin)
    b = text.index(end, a)
    return text[:a] + body + text[b:]


def main():
    check = "--check" in sys.argv
    langs = json.loads(SOURCE.read_text(encoding="utf-8"))["languages"]
    validate(langs)
    jobs = [
        (ROOT / "components/app_display/src/Format.cpp",
         [("// texts: begin", "// texts: end", "\n" + cpp(langs) + "\n")]),
        (ROOT / "www/index.html",
         [("// texts: begin", "// texts: end", "\n" + js(langs) + "\n"),
          ("<!-- texts: begin -->", "<!-- texts: end -->", options(langs))]),
        (ROOT / "components/panel/src/Schema.cpp",
         [("// texts: begin", "    // texts: end", "\n" + schema(langs) + "\n")]),
    ]
    stale = []
    for path, parts in jobs:
        text = path.read_text(encoding="utf-8")
        new = text
        for begin, end, body in parts:
            new = splice(new, begin, end, body, path)
        if new != text:
            stale.append(path.relative_to(ROOT))
            if not check:
                path.write_text(new, encoding="utf-8")
    if check and stale:
        sys.exit("gen_texts: not current, run tools/gen_texts.py: " + ", ".join(map(str, stale)))
    print("gen_texts: " + ("written " + ", ".join(map(str, stale)) if stale and not check else "current"))


if __name__ == "__main__":
    main()
